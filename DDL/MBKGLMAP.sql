--* ENVIRONMENT - A RERUN FAILS -803 ON INDEX XGLMP01. CHANGES AFTER  *
--* GO-LIVE ARE MADE BY FINANCE (SQLID MBKFINC, SPUFI + CR) BY        *
--* CLOSING THE OLD ROW (EFFECTIVE_TO) AND INSERTING A NEW ONE - NEVER*
