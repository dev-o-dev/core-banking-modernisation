--* DR_CR_IND IS THE CUSTOMER SIDE: 'D' = CUSTOMER DEBITED, CONTRA    *
--* CREDITED; 'C' = CUSTOMER CREDITED, CONTRA DEBITED.                *
--*                                                                   *
--* MAP_ACTION (SEE GLEXT010 HEADER)                                  *
--*   P  POST THE CONTRA BELOW                                        *
--*   S  SKIP - ALREADY JOURNALED AT SOURCE (INT, TAX, CHG).          *
--*      CONTRA_GL IS INFORMATION ONLY                                *
--*   I  INTERNAL - BOTH SIDES ARE CUSTOMER ACCOUNTS (TFR, REV, OPN,  *
--*      CLS). GLEXT010 USES THE TRANSFER CLEARING ACCOUNT 19000-0001 *
--*      WHICH MUST NET TO ZERO                                       *
--* UNMAPPED MOVEMENTS GO TO SUSPENSE 29900-0001 (MBK.GLSUSP).        *
--*                                                                   *
--* CONTRA ACCOUNTS (CHART OF ACCOUNTS 2002)                          *
--*   10100-0010 CASH - BRANCHES AND ATMS                             *
--*   11200-0010 NOSTRO - SWIFT CORRESPONDENT BANKS                   *
--*   13000-0010 PERSONAL LOANS - PRINCIPAL                           *
--*   18100-0010 FASTER PAYMENTS SETTLEMENT                           *
--*   18100-0020 BACS SETTLEMENT                                      *
--*   18100-0030 CHAPS (RTGS) SETTLEMENT                              *
--*   18200-0010 CARD SCHEME SETTLEMENT                               *
--*   18300-0010 CHEQUE CLEARING - INWARD (ITEMS DRAWN ON US)         *
--*   18300-0020 CHEQUE CLEARING - OUTWARD (DEPOSITED ITEMS)          *
--*   19000-0001 INTERNAL TRANSFER CLEARING                           *
--*   28100-0010 INCOME TAX PAYABLE - HMRC              (S ROWS)      *
--*   41000-0010 INTEREST INCOME - OVERDRAFTS           (S ROWS)      *
--*   42100-0010 FEE AND COMMISSION INCOME              (S ROWS)      *
--*   51000-0010 INTEREST EXPENSE - CUSTOMER DEPOSITS   (S ROWS)      *
