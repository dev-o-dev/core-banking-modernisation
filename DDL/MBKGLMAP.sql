--*   600100 BRANCH CASH OPERATIONS    710100 PAYMENTS OPERATIONS     *
--*   720100 CARD OPERATIONS           730100 CHEQUE OPERATIONS       *
--*   810100 LENDING OPERATIONS                                       *
--*-------------------------------------------------------------------*
--* KNOWN GAPS (RAISED WITH FINANCE)                                  *
--* - CHG 'S': THE SWIFT/CHAPS FEES RAISED ONLINE BY PYINIT1 AND THE  *
--*   NON-STERLING CARD FEES FROM CDSTL010 ARE NOT JOURNALED AT       *
--*   SOURCE, SO THEY NEVER REACH FEE INCOME.                         *
--* - REV 'I': A REVERSAL OF AN EXTERNAL PAYMENT (E.G. PYFPRSP AFTER  *
--*   AN FPS REJECT) IS BOOKED THROUGH 19000-0001, WHICH THEN DOES    *
--*   NOT NET TO ZERO. FINANCE CLEAR THE DIFFERENCE BY HAND.          *
--* - SO: INTERNAL SOS (ROUTE I) AND FPS SOS SHARE ONE CONTRA; THE    *
--*   TWO LEGS OF AN INTERNAL SO NET OFF IN 18100-0010.               *
